function generate(rng) {
  const rows = [];
  const famPool = FAMILIES;
  const symbolPool = ELEMENTS.map((e) => e[1]);
  const numberPool = ELEMENTS.map((e) => String(e[2]));

  for (const [name, symbol, number, family] of ELEMENTS) {
    rows.push({
      q: `What is the chemical symbol for ${name}?`,
      correct: symbol,
      ds: distractors(symbolPool, symbol, 3, rng),
      level: 'medium',
      chapter: CHAPTERS.chem,
    });
    rows.push({
      q: `What is the atomic number of ${name}?`,
      correct: String(number),
      ds: distractors(numberPool, String(number), 3, rng),
      level: 'hard',
      chapter: CHAPTERS.chem,
    });
    rows.push({
      q: `To which element family does ${name} belong?`,
      correct: family,
      ds: distractors(
        famPool.filter((f) => f !== family),
        family,
        3,
        rng
      ),
      level: 'medium',
      chapter: CHAPTERS.chem,
    });
  }

  const BANKS = [
    SPACE,
    PHYSICS,
    CHEMISTRY,
    BODY,
    EARTH,
    NATURE,
    SCIENTISTS,
    UNITS,
    INVENTIONS,
    MEDICINE,
    DISCOVERIES,
  ];
  for (const bank of BANKS) {
    for (const f of bank)
      rows.push({ q: f[0], correct: f[1], ds: [f[2], f[3], f[4]], level: f[5], chapter: f[6] });
  }

  for (const [q, text, chapter] of EXTREMES) rows.push({ q, text, chapter });

  return rows;
}


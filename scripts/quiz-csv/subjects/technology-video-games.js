function generate(rng) {
  const rows = [];

  const founderPool = COMPANIES.map((c) => c[1]);
  const productPool = COMPANIES.map((c) => c[3]);
  const hqPool = COMPANIES.map((c) => c[2]);
  for (const [company, founder, hq, product] of COMPANIES) {
    rows.push({
      q: `Who founded ${company}?`,
      correct: founder,
      ds: distractors(founderPool, founder, 3),
      level: 'medium',
      chapter: 'Tech Companies',
    });
    rows.push({
      q: `Which country is ${company} headquartered in?`,
      correct: hq,
      ds: distractors(hqPool, hq, 3),
      level: 'medium',
      chapter: 'Tech Companies',
    });
    rows.push({
      q: `What is ${company} best known for?`,
      correct: product,
      ds: distractors(productPool, product, 3),
      level: 'hard',
      chapter: 'Tech Companies',
    });
  }

  const usePool = PROGRAMMING.map((p) => p[1]);
  for (const [lang, use] of PROGRAMMING) {
    rows.push({
      q: `What is ${lang} primarily used for?`,
      correct: use,
      ds: distractors(usePool, use, 3),
      level: 'medium',
      chapter: 'Programming',
    });
    rows.push({
      q: `Which language is primarily used for ${use}?`,
      correct: lang,
      ds: PROGRAMMING.filter((p) => p[0] !== lang)
        .slice(0, 3)
        .map((p) => p[0]),
      level: 'hard',
      chapter: 'Programming',
    });
  }

  const makerPool = CONSOLES.map((c) => c[1]);
  for (const [console, maker] of CONSOLES) {
    rows.push({
      q: `Which company made the ${console}?`,
      correct: maker,
      ds: distractors(makerPool, maker, 3),
      level: 'easy',
      chapter: 'Consoles',
    });
    rows.push({
      q: `Name a console made by ${maker}.`,
      correct: console,
      ds: CONSOLES.filter((c) => c[1] !== maker)
        .slice(0, 3)
        .map((c) => c[0]),
      level: 'medium',
      chapter: 'Consoles',
    });
  }

  const devPool = GAMES.map((g) => g[1]);
  const yearPool = GAMES.map((g) => String(g[2]));
  for (const [game, dev, year] of GAMES) {
    rows.push({
      q: `Who developed or published ${game}?`,
      correct: dev,
      ds: distractors(devPool, dev, 3),
      level: 'medium',
      chapter: 'Video Games',
    });
    rows.push({
      q: `In which year did ${game} release?`,
      correct: String(year),
      ds: distractors(yearPool, String(year), 3),
      level: 'hard',
      chapter: 'Video Games',
    });
    rows.push({
      q: `Which game was released by ${dev} in ${year}?`,
      correct: game,
      ds: GAMES.filter((g) => g[0] !== game)
        .slice(0, 3)
        .map((g) => g[0]),
      level: 'hard',
      chapter: 'Video Games',
    });
  }

  const BANKS = [
    INTERNET,
    HARDWARE,
    ACRONYMS_TECH,
    TECH_HISTORY,
    GAMING_MORE,
    TECH_MORE,
    GAMING_TOPUP,
  ];
  for (const f of topup.rows)
    rows.push({ q: f[0], correct: f[1], ds: [f[2], f[3], f[4]], level: f[5], chapter: f[6] });
  for (const bank of BANKS) {
    for (const f of bank)
      rows.push({ q: f[0], correct: f[1], ds: [f[2], f[3], f[4]], level: f[5], chapter: f[6] });
  }

  for (const [q, text, chapter] of EXTREMES) rows.push({ q, text, chapter });

  return rows;
}

module.exports = { subject: 'Technology & Video Games', generate };

function generate(rng) {
  const rows = [];

  const wcYears = WORLD_CUPS.map((w) => String(w[0]));
  const wcHosts = WORLD_CUPS.map((w) => w[1]);
  const wcWinners = WORLD_CUPS.map((w) => w[2]);
  const wcRunners = WORLD_CUPS.map((w) => w[3]);

  for (const [year, host, winner, runner] of WORLD_CUPS) {
    rows.push({
      q: `Which country won the ${year} FIFA World Cup?`,
      correct: winner,
      ds: distractors(wcWinners, winner, 3, rng),
      level: 'medium',
      chapter: 'Football & World Cup',
    });
    rows.push({
      q: `Which country hosted the ${year} FIFA World Cup?`,
      correct: host,
      ds: distractors(wcHosts, host, 3, rng),
      level: 'medium',
      chapter: 'Football & World Cup',
    });
    rows.push({
      q: `Which team was runner-up in the ${year} FIFA World Cup final?`,
      correct: runner,
      ds: distractors([...new Set([...wcRunners, ...wcWinners])], runner, 3, rng),
      level: 'hard',
      chapter: 'Football & World Cup',
    });
  }
  // Reverse-year questions for one- and two-time champions.
  const winsByTeam = {};
  for (const [year, , winner] of WORLD_CUPS)
    (winsByTeam[winner] = winsByTeam[winner] || []).push(year);
  for (const team of Object.keys(winsByTeam)) {
    if (winsByTeam[team].length <= 2) {
      for (const y of winsByTeam[team]) {
        rows.push({
          q: `In which year did ${team} win a FIFA World Cup?`,
          correct: String(y),
          ds: distractors(wcYears, String(y), 3, rng),
          level: 'hard',
          chapter: 'Football & World Cup',
        });
      }
    }
  }

  const olyYears = SUMMER_OLYMPICS.map((o) => String(o[0]));
  const olyCities = SUMMER_OLYMPICS.map((o) => o[1]);
  for (const [year, city] of SUMMER_OLYMPICS) {
    rows.push({
      q: `Which city hosted the ${year} Summer Olympics?`,
      correct: city,
      ds: distractors(olyCities, city, 3, rng),
      level: 'medium',
      chapter: 'Olympics',
    });
    rows.push({
      q: `In which year did ${city} host a Summer Olympics edition shown in our list?`,
      correct: String(year),
      ds: distractors(olyYears, String(year), 3, rng),
      level: 'hard',
      chapter: 'Olympics',
    });
  }

  const countries = FOOTBALLERS.map((p) => p[1]);
  const clubs = FOOTBALLERS.map((p) => p[2]);
  const names = FOOTBALLERS.map((p) => p[0]);
  for (const [player, country, club] of FOOTBALLERS) {
    rows.push({
      q: `Which country does ${player} play for?`,
      correct: country,
      ds: distractors(countries, country, 3, rng),
      level: 'easy',
      chapter: 'Football & World Cup',
    });
    rows.push({
      q: `Which club is ${player} most famous for?`,
      correct: club,
      ds: distractors(clubs, club, 3, rng),
      level: 'medium',
      chapter: 'Football & World Cup',
    });
    rows.push({
      q: `Which legendary player is most associated with ${club}?`,
      correct: player,
      ds: distractors(names, player, 3, rng),
      level: 'hard',
      chapter: 'Football & World Cup',
    });
  }

  const clubNames = CLUBS.map((c) => c[0]);
  const clubCountries = CLUBS.map((c) => c[1]);
  const stadiums = CLUBS.map((c) => c[2]);
  for (const [club, country, stadium] of CLUBS) {
    rows.push({
      q: `Which country does ${club} play in?`,
      correct: country,
      ds: distractors(clubCountries, country, 3, rng),
      level: 'easy',
      chapter: 'Football & World Cup',
    });
    rows.push({
      q: `What is the home stadium of ${club}?`,
      correct: stadium,
      ds: distractors(stadiums, stadium, 3, rng),
      level: 'hard',
      chapter: 'Football & World Cup',
    });
    rows.push({
      q: `Which famous club plays home games at ${stadium}?`,
      correct: club,
      ds: distractors(clubNames, club, 3, rng),
      level: 'hard',
      chapter: 'Football & World Cup',
    });
  }

  const BANKS = [
    FOOTBALL_FACTS,
    OLYMPIC_FACTS,
    CRICKET,
    TENNIS,
    AMERICAN,
    MORE_SPORTS,
    BASICS,
    NICKNAMES,
    LEGENDS,
    ATHLETES,
    STADIUMS,
    RULES_MORE,
    SPORTS_HISTORY,
  ];
  for (const bank of BANKS) {
    for (const f of bank)
      rows.push({ q: f[0], correct: f[1], ds: [f[2], f[3], f[4]], level: f[5], chapter: f[6] });
  }

  for (const [q, text, chapter] of EXTREMES) rows.push({ q, text, chapter });

  return rows;
}


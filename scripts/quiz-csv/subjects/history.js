function centuryOf(year) {
  if (year < 0) return 'The 1st century BC';
  const c = Math.floor((year - 1) / 100) + 1;
  const s =
    ['th', 'st', 'nd', 'rd'][((c % 100) - 20) % 10] || ['th', 'st', 'nd', 'rd'][c % 100] || 'th';
  return `The ${c}${s} century`;
}

function generate(rng) {
  const rows = [];
  const yearPool = EVENTS.map((e) => String(e[1]));
  const placePool = EVENTS.map((e) => e[2]);
  const centuryPool = [...new Set(EVENTS.map((e) => centuryOf(e[1])))];

  for (const [event, year, place] of EVENTS) {
    rows.push({
      q: `In which year did ${event} happen?`,
      correct: String(year),
      ds: distractors(yearPool, String(year), 3, rng),
      level: 'medium',
      chapter: 'Events & Dates',
    });
    rows.push({
      q: `Where did ${event} take place?`,
      correct: place,
      ds: distractors(placePool, place, 3, rng),
      level: 'medium',
      chapter: 'Events & Places',
    });
    const cent = centuryOf(year);
    rows.push({
      q: `In which century did ${event} happen?`,
      correct: cent,
      ds: distractors(
        centuryPool.filter((c) => c !== cent),
        cent,
        3,
        rng
      ),
      level: 'medium',
      chapter: 'Events & Dates',
    });
  }

  const BANKS = [
    ANCIENT,
    WARS,
    LEADERS,
    MODERN,
    EXPLORERS,
    FIRSTS,
    EMPIRES,
    US_HISTORY,
    WORLD_HISTORY,
    ERAS,
    TIMELINES,
  ];
  const lc = (s) => (s.startsWith('The ') ? 'the ' + s.slice(4) : s);
  // "Which came first?" rows share question text — rephrase each uniquely.
  const processedBanks = BANKS.map((bank) =>
    bank.map((f) =>
      f[0] === 'Which came first?'
        ? [`Which came first, ${lc(f[2])} or ${lc(f[1])}?`, f[1], f[2], f[3], f[4], f[5], f[6]]
        : f
    )
  );
  for (const bank of processedBanks) {
    for (const f of bank)
      rows.push({ q: f[0], correct: f[1], ds: [f[2], f[3], f[4]], level: f[5], chapter: f[6] });
  }

  for (const [q, text, chapter] of EXTREMES) rows.push({ q, text, chapter });

  return rows;
}


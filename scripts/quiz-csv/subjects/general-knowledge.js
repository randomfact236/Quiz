function generate(rng) {
  const rows = [];

  // Language questions (dedupe the accidental duplicate entry by unique text below)
  const langPool = LANGUAGES.map((l) => l[1]);
  for (const [country, lang] of LANGUAGES) {
    rows.push({
      q: `What is the main language or languages of ${country}?`,
      correct: lang,
      ds: distractors(langPool, lang, 3, rng),
      level: 'medium',
      chapter: 'Languages & Nations',
    });
  }

  const romanPool = ROMAN.map((r) => r[1]);
  for (const [num, roman] of ROMAN) {
    rows.push({
      q: `What is ${num} in Roman numerals?`,
      correct: roman,
      ds: distractors(romanPool, roman, 3, rng),
      level: 'medium',
      chapter: 'Numbers & Math',
    });
    rows.push({
      q: `What number is the Roman numeral ${roman}?`,
      correct: String(num),
      ds: distractors(
        ROMAN.map((r) => String(r[0])),
        String(num),
        3,
        rng
      ),
      level: 'medium',
      chapter: 'Numbers & Math',
    });
  }

  const sqPool = SQUARES.map((s) => String(s[1]));
  const rootPool = SQUARES.map((s) => String(s[0]));
  for (const [n, sq] of SQUARES) {
    rows.push({
      q: `What is ${n} squared?`,
      correct: String(sq),
      ds: distractors(sqPool, String(sq), 3, rng),
      level: 'easy',
      chapter: 'Numbers & Math',
    });
    rows.push({
      q: `What is the square root of ${sq}?`,
      correct: String(n),
      ds: distractors(rootPool, String(n), 3, rng),
      level: 'easy',
      chapter: 'Numbers & Math',
    });
  }

  const mixPool = COLOR_MIX.map((c) => c[2]);
  for (const [a, b, mix] of COLOR_MIX) {
    rows.push({
      q: `What color do you get mixing ${a} and ${b}?`,
      correct: mix,
      ds: distractors(mixPool, mix, 3, rng),
      level: 'easy',
      chapter: 'Colors & Symbols',
    });
  }

  const symbolMeanings = SYMBOLS.map((s) => s[1]);
  for (const [symbol, meaning] of SYMBOLS) {
    rows.push({
      q: `What does ${symbol} represent?`,
      correct: meaning,
      ds: distractors(symbolMeanings, meaning, 3, rng),
      level: 'medium',
      chapter: 'Colors & Symbols',
    });
  }

  const answerPool = BOARD_GAMES.map((b) => b[1]);
  for (const [q, correct, d1, d2, d3, level] of BOARD_GAMES) {
    rows.push({ q, correct, ds: [d1, d2, d3], level, chapter: 'Games & Pastimes' });
  }

  const BANKS = [WORLD_BASICS, TOPUP];
  for (const bank of BANKS) {
    for (const f of bank)
      rows.push({ q: f[0], correct: f[1], ds: [f[2], f[3], f[4]], level: f[5], chapter: f[6] });
  }

  // Large flat banks from the companion module (unique texts inside).
  for (const f of extra.rows) rows.push(f);

  return rows;
}


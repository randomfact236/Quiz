function generate(rng) {
  const rows = [];

  const countryPool = DISHES.map((d) => d[1]);
  const ingredientPool = DISHES.map((d) => d[2]);
  const typePool = DISHES.map((d) => d[3]);
  for (const [dish, country, ingredient, type] of DISHES) {
    rows.push({
      q: `Which cuisine does ${dish} belong to?`,
      correct: country,
      ds: distractors(countryPool, country, 3),
      level: 'easy',
      chapter: 'World Dishes',
    });
    rows.push({
      q: `What is ${dish} mainly made of?`,
      correct: ingredient,
      ds: distractors(ingredientPool, ingredient, 3),
      level: 'medium',
      chapter: 'World Dishes',
    });
    rows.push({
      q: `What kind of dish is ${dish}?`,
      correct: type,
      ds: distractors(typePool, type, 3),
      level: 'medium',
      chapter: 'World Dishes',
    });
  }

  const factPool = FRUITS.map((f) => f[1]);
  for (const [fruit, fact] of FRUITS) {
    rows.push({
      q: `What is a notable fact about ${fruit}?`,
      correct: fact,
      ds: distractors(factPool, fact, 3),
      level: 'medium',
      chapter: 'Fruits & Vegetables',
    });
  }
  const vegPool = VEGETABLES.map((v) => v[1]);
  for (const [veg, part] of VEGETABLES) {
    rows.push({
      q: `What part of the plant is ${veg}?`,
      correct: part,
      ds: distractors(vegPool, part, 3),
      level: 'medium',
      chapter: 'Fruits & Vegetables',
    });
  }

  const sourcePool = HERBS_SPICES.map((h) => h[1]);
  for (const [herb, source] of HERBS_SPICES) {
    rows.push({
      q: `Where does ${herb} come from?`,
      correct: source,
      ds: distractors(sourcePool, source, 3),
      level: 'medium',
      chapter: 'Herbs & Spices',
    });
  }
  const cheesePool = CHEESES.map((c) => c[1]);
  for (const [cheese, origin] of CHEESES) {
    rows.push({
      q: `What is ${cheese}?`,
      correct: origin,
      ds: distractors(cheesePool, origin, 3),
      level: 'medium',
      chapter: 'Cheeses',
    });
  }
  const shapePool = PASTAS.map((p) => p[1]);
  for (const [pasta, desc] of PASTAS) {
    rows.push({
      q: `What shape is ${pasta}?`,
      correct: desc,
      ds: distractors(shapePool, desc, 3),
      level: 'medium',
      chapter: 'Pasta Shapes',
    });
    rows.push({
      q: `Which pasta is described as ${desc}?`,
      correct: pasta,
      ds: PASTAS.filter((p) => p[0] !== pasta)
        .slice(0, 3)
        .map((p) => p[0]),
      level: 'hard',
      chapter: 'Pasta Shapes',
    });
  }

  const BANKS = [TECHNIQUES, BAKING, DRINKS, NUTRITION, KITCHEN_TOOLS, FLAT, FOOD_MORE];
  for (const bank of BANKS) {
    for (const f of bank)
      rows.push({ q: f[0], correct: f[1], ds: [f[2], f[3], f[4]], level: f[5], chapter: f[6] });
  }

  for (const f of topup.rows)
    rows.push({ q: f[0], correct: f[1], ds: [f[2], f[3], f[4]], level: f[5], chapter: f[6] });
  for (const f of topup2.rows)
    rows.push({ q: f[0], correct: f[1], ds: [f[2], f[3], f[4]], level: f[5], chapter: f[6] });
  for (const [q, text, chapter] of EXTREMES) rows.push({ q, text, chapter });

  return rows;
}

module.exports = { subject: 'Food & Cooking', generate };

function generate(rng) {
  const rows = [];

  const countryPool = ARTISTS.map((a) => a[1]);
  const genrePool = ARTISTS.map((a) => a[2]);
  const songPool = ARTISTS.map((a) => a[3]);
  for (const [artist, country, genre, song] of ARTISTS) {
    rows.push({
      q: `Which country is ${artist} from?`,
      correct: country,
      ds: distractors(countryPool, country, 3),
      level: 'easy',
      chapter: 'Artists',
    });
    rows.push({
      q: `What genre is ${artist} best known for?`,
      correct: genre,
      ds: distractors(genrePool, genre, 3),
      level: 'medium',
      chapter: 'Artists',
    });
    rows.push({
      q: `Which song is ${artist} most iconic for?`,
      correct: song,
      ds: distractors(songPool, song, 3),
      level: 'hard',
      chapter: 'Artists',
    });
  }

  const bandCountryPool = BANDS.map((b) => b[1]);
  const albumPool = BANDS.map((b) => b[2]);
  for (const [band, country, album] of BANDS) {
    rows.push({
      q: `Which country is the band ${band} from?`,
      correct: country,
      ds: distractors(bandCountryPool, country, 3),
      level: 'medium',
      chapter: 'Bands',
    });
    rows.push({
      q: `Which album is ${band} most famous for?`,
      correct: album,
      ds: distractors(albumPool, album, 3),
      level: 'hard',
      chapter: 'Bands',
    });
  }

  const familyPool = INSTRUMENTS.map((i) => i[1]);
  for (const [instrument, family] of INSTRUMENTS) {
    rows.push({
      q: `To which instrument family does ${instrument} belong?`,
      correct: family,
      ds: distractors(familyPool, family, 3),
      level: 'easy',
      chapter: 'Instruments',
    });
    rows.push({
      q: `Which of these is a member of the ${family} family?`,
      correct: instrument,
      ds: INSTRUMENTS.filter((i) => i[1] !== family)
        .slice(0, 3)
        .map((i) => i[0]),
      level: 'medium',
      chapter: 'Instruments',
    });
  }

  const compCountryPool = CLASSICAL.map((c) => c[1]);
  const workPool = CLASSICAL.map((c) => c[2]);
  for (const [composer, country, work] of CLASSICAL) {
    rows.push({
      q: `Which country was ${composer} from?`,
      correct: country,
      ds: distractors(compCountryPool, country, 3),
      level: 'medium',
      chapter: 'Classical',
    });
    rows.push({
      q: `Which work is ${composer} famous for?`,
      correct: work,
      ds: distractors(workPool, work, 3),
      level: 'hard',
      chapter: 'Classical',
    });
  }

  const BANKS = [
    SONGS_ALBUMS,
    GENRES,
    THEORY,
    AWARDS_CHARTS,
    LEGENDS,
    WORLD_MUSIC,
    MUSIC_MORE,
    TOPUP2,
  ];

  const hitYearPool = DECADE_HITS.map((h) => String(h[0]));
  const hitArtistPool = DECADE_HITS.map((h) => h[2]);
  for (const [year, song, artist] of DECADE_HITS) {
    rows.push({
      q: `Who recorded ${song}?`,
      correct: artist,
      ds: distractors(hitArtistPool, artist, 3),
      level: 'medium',
      chapter: 'Decade Hits',
    });
    rows.push({
      q: `In which year was ${song} a major hit?`,
      correct: String(year),
      ds: distractors(hitYearPool, String(year), 3),
      level: 'medium',
      chapter: 'Decade Hits',
    });
  }
  for (const bank of BANKS) {
    for (const f of bank)
      rows.push({ q: f[0], correct: f[1], ds: [f[2], f[3], f[4]], level: f[5], chapter: f[6] });
  }

  for (const [q, text, chapter] of EXTREMES) rows.push({ q, text, chapter });

  return rows;
}

module.exports = { subject: 'Music', generate };
